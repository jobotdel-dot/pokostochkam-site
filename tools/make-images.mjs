function drawText(rgb, w, h, text, x0, y0, scale, color, spacing = 1) {
  let x = x0;
  for (const ch of text.toUpperCase()) {
    const g = GLYPHS[ch] || GLYPHS[" "];
    for (let r = 0; r < g.length; r++) {
      for (let c = 0; c < g[r].length; c++) {
        if (g[r][c] !== "1") continue;
        for (let dy = 0; dy < scale; dy++) {
          for (let dx = 0; dx < scale; dx++) {
            const px = x + c * scale + dx;
            const py = y0 + r * scale + dy;
            if (px < 0 || py < 0 || px >= w || py >= h) continue;
            const o = (py * w + px) * 3;
            rgb[o] = color[0]; rgb[o + 1] = color[1]; rgb[o + 2] = color[2];
          }
        }
      }
    }
    x += (5 + spacing) * scale;
  }
  return x;
}

const textWidth = (text, scale, spacing = 1) => text.length * (5 + spacing) * scale;

// ---------- og-image: 1200x630 ----------
const W = 1200, H = 630;
const img = Buffer.alloc(W * H * 3);
// фон: тёмный бирюзовый (совпадает с --brand #0f766e)
for (let i = 0; i < W * H; i++) {
  img[i * 3] = 15; img[i * 3 + 1] = 118; img[i * 3 + 2] = 110;
}
// светлая полоса снизу
for (let y = H - 90; y < H; y++) {
  for (let x = 0; x < W; x++) {
    const o = (y * W + x) * 3;
    img[o] = 240; img[o + 1] = 253; img[o + 2] = 250;
  }
}
// декоративные точки «косточки»
for (let i = 0; i < 26; i++) {
  const cx = 60 + ((i * 137) % (W - 120));
  const cy = 70 + ((i * 83) % 380);
  const r = 3 + (i % 4);
  for (let y = cy - r; y <= cy + r; y++) {
    for (let x = cx - r; x <= cx + r; x++) {
      if (x < 0 || y < 0 || x >= W || y >= H) continue;
      const d = Math.hypot(x - cx, y - cy);
      if (d > r) continue;
      const o = (y * W + x) * 3;
      img[o] = 153; img[o + 1] = 246; img[o + 2] = 228;
    }
  }
}
